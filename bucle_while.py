# ===========================================
# BUCLE WHILE
# ===========================================

# Creamos un contador
contador = 1

# Mientras el contador sea menor o igual a 5
while contador <= 5:

    # Mostramos el valor del contador
    print(contador)

    # Sumamos 1 al contador
    contador += 1

# Cuando el contador llega a 6 el ciclo termina