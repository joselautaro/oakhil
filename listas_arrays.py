# LISTAS (ARRAYS)
# ===========================================

# Creamos una lista con nombres
alumnos = ["Juan", "María", "Pedro", "Ana"]

# Mostramos toda la lista
print(alumnos)

# Mostramos el primer elemento
print(alumnos[0])

# Agregamos un nuevo alumno
alumnos.append("Carlos")

# Recorremos toda la lista
for alumno in alumnos:

    # Mostramos cada nombre
    print(alumno)