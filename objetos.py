# Creamos un objeto con información de un alumno
alumno = {
    "nombre": "Juan",
    "edad": 17,
    "curso": "5° A"
}

# Mostramos cada dato
print(alumno["nombre"])
print(alumno["edad"])
print(alumno["curso"])

# Agregamos un nuevo dato
alumno["promedio"] = 8.75

# Mostramos nuevamente el objeto
print(alumno)